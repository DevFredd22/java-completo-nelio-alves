package praticas;

public class A008_Estrutura_Repeticao_For {
	
	public static void main(String[] args) {
		
		//FOR é utilizado quando sabemos quando nosso programa dever parar...No exemplo abaixo a base é o 10

		int start = 10;
		for(int limite = 0;limite<=start;limite++) { System.out.println(limite); }
	}

}
